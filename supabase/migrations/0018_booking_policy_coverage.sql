create function private.validate_event_address(address jsonb) returns jsonb language plpgsql stable set search_path='' as $$
declare p private.coverage_places; c private.coverage_places; b private.coverage_places; contact text;
begin
 select * into p from private.coverage_places where code=address->>'province_code' and level='province';
 if not found or p.name not in ('Bulacan','Pampanga') or coalesce(address->>'province','')<>p.name then raise exception 'Event locations are restricted to Bulacan and Pampanga'; end if;
 select * into c from private.coverage_places where code=address->>'city_code' and parent_code=p.code and level='city';
 if not found or coalesce(address->>'city','')<>c.name then raise exception 'Choose a real city or municipality in the selected province'; end if;
 select * into b from private.coverage_places where code=address->>'barangay_code' and parent_code=c.code and level='barangay';
 if not found or coalesce(address->>'barangay','')<>b.name then raise exception 'Choose a real barangay in the selected city or municipality'; end if;
 contact=regexp_replace(coalesce(address->>'contact',''),'[^+0-9]','','g');
