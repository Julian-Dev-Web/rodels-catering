  if n>50000 then raise exception 'Dataset too large for application export; use a PostgreSQL backup'; end if;
  tables=tables||jsonb_build_object(t,rows); counts=counts||jsonb_build_object(t,n);
  if octet_length(tables::text)>10485760 then raise exception 'Dataset too large for application export; use a PostgreSQL backup'; end if;
 end loop;
 result=jsonb_build_object('format','rodelconnect-application-export','version',1,'schema_version','0018_booking_policy_coverage.sql','captured_at',statement_timestamp(),'scope','Public application records only; migrations are required to interpret or restore these records.','exclusions',jsonb_build_array('Supabase Auth accounts and credentials','Storage file contents','Server secrets and deployment settings','Platform Auth/Storage internals and database role credentials'),'counts',counts,'tables',tables);
 return result;
end $$;
