create function private.validate_event_preferences(setup uuid,prefs jsonb) returns jsonb language plpgsql stable set search_path='' as $$
declare kind text; allowed text[]='{}'; selected text[]; age int; theme text; colors text; occasion text;
begin
 if prefs is null or jsonb_typeof(prefs)<>'object' then raise exception 'Invalid event preferences'; end if;
 select setup_kind into kind from public.event_setups where id=setup and active;
 if kind='birthday' then allowed=array['stage_backdrop','elegant_chair','entrance']; elsif kind='wedding' then allowed=array['stage_backdrop','elegant_chair','entrance','presidential_table','buffet_setup','diamond_dance_floor']; end if;
 if prefs ? 'setup_inclusions' then
  if jsonb_typeof(prefs->'setup_inclusions')<>'array' then raise exception 'Invalid setup inclusions'; end if;
  select coalesce(array_agg(value),'{}') into selected from jsonb_array_elements_text(prefs->'setup_inclusions');
 else selected=allowed; end if;
 if not selected <@ allowed or cardinality(selected)<>(select count(distinct x) from unnest(selected)x) then raise exception 'Invalid setup inclusions'; end if;
 if kind='wedding' and cardinality(selected)<>6 and not private.valid_wedding_prices(public.wedding_price_configuration()) then raise exception 'Wedding price breakdown pending; select all six inclusions for the PHP 30,000 full bundle'; end if;
 if coalesce(prefs->>'celebrant_age','')<>'' then
  if (prefs->>'celebrant_age') !~ '^[0-9]{1,3}$' then raise exception 'Celebrant age must be a positive integer'; end if;
  age=(prefs->>'celebrant_age')::int; if age not between 1 and 120 then raise exception 'Celebrant age must be between 1 and 120'; end if;
 end if;
 theme=btrim(coalesce(prefs->>'theme','')); colors=btrim(coalesce(prefs->>'colors','')); occasion=coalesce(prefs->>'occasion_type',case when kind in ('birthday','wedding') then kind else 'other' end);
 if occasion not in ('birthday','wedding','other') or length(theme)>200 or length(colors)>200 then raise exception 'Check occasion, theme and color preferences'; end if;
 return jsonb_build_object('occasion_type',occasion,'theme',theme,'colors',colors,'celebrant_age',age,'setup_inclusions',to_jsonb(selected));
end $$;
