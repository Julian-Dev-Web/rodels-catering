import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import ts from 'typescript'

// Read the same owner-supplied choices used by the unconfigured UI preview.
const source = await readFile(new URL('../src/data/rodels-menu.ts', import.meta.url), 'utf8')
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText
const catalog = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'))
const id = (table, name) => {
  const hash = createHash('md5').update('rodels-confirmed-2026-10-15:' + table + ':' + name).digest('hex')
  return `${hash.slice(0,8)}-${hash.slice(8,12)}-${hash.slice(12,16)}-${hash.slice(16,20)}-${hash.slice(20)}`
}
const literal = value => value === null ? 'null' : typeof value === 'number' ? String(value) : "'" + String(value).replaceAll("'", "''") + "'"
const parts = ['-- GENERATED by npm run db:catalog. Owner-confirmed catalog, October 15, 2026.', '-- New choices replace the illustrative catalog. Archive rows; never delete bookings or financial history.']
function rows(table, entries) {
  const keys = ['id', ...Object.keys(entries[0])]
  const values = entries.map(entry => '(' + keys.map(key => {
    if (key === 'id') return literal(id(table, entry.name))
    if (key === 'inclusions') return 'array[' + entry[key].map(literal).join(',') + ']::text[]'
    if (key === 'suggested_dishes') return literal(JSON.stringify(entry[key])) + '::jsonb'
    return literal(entry[key])
  }).join(',') + ')')
  const ids = entries.map(entry => literal(id(table, entry.name))).join(',')
  parts.push(`update public.${table} set active=false where id not in (${ids}) and active;`)
  parts.push(`insert into public.${table}(${keys.join(',')}) values\n${values.join(',\n')}\non conflict(id) do update set ${keys.filter(k=>k!=='id').map(k=>`${k}=excluded.${k}`).join(',')},active=true;`)
}
rows('menu_sets', catalog.rodelsMenus)
rows('menu_categories', Object.keys(catalog.rodelsFoods).map(name => ({ name })))
// Include additional choices explicitly shown in the suggested set-menu photo.
const foods = structuredClone(catalog.rodelsFoods)
rows('dishes', Object.entries(foods).flatMap(([category,names]) => names.map(name => ({name,category_id:id('menu_categories',category)}))))
rows('drinks', catalog.rodelsDrinks.map(name=>({name})))
rows('desserts', catalog.rodelsDesserts.map(name=>({name})))
rows('event_setups', catalog.rodelsSetups)
rows('event_features', [{name:'Glass dance floor upgrade',price:500000,required_setup_id:id('event_setups','Wedding setup')},{name:'Trusses',price:4500000,required_setup_id:null}])
parts.push('update public.add_ons set active=false where active;')
rows('chair_types', catalog.rodelsChairs)
rows('table_types', catalog.rodelsTables)
// Retain recognizable archived fixtures and their old rates for legacy quotes.
parts.push(`update public.chair_types set name=name||' (legacy)' where not active and name in ('Monoblock','Tiffany');`)
parts.push("notify pgrst, 'reload schema';")
await writeFile(new URL('../supabase/migrations/0015_rodels_catalog.sql', import.meta.url), parts.join('\n\n')+'\n')
console.log(JSON.stringify({menus:catalog.rodelsMenus.length,dishes:Object.values(foods).flat().length,drinks:catalog.rodelsDrinks.length,desserts:catalog.rodelsDesserts.length}))
